export type BbsAiRequest = {
  prompt: string
  currentHtml?: string
}

export type BbsAiResponse = {
  html: string
  source: 'bbs-ai-model' | 'fallback'
}

type BbsAiModelResponse = {
  html?: string
  content?: string
  result?: string
}

const ENGINE_URL = process.env.BBS_AI_ENGINE_URL

function cleanHtml(value: string): string {
  let html = String(value || '').trim()

  // Remove markdown code fences if a model accidentally returns them.
  html = html.replace(/^```html\s*/i, '')
  html = html.replace(/^```HTML\s*/i, '')
  html = html.replace(/^```\s*/i, '')
  html = html.replace(/\s*```$/i, '')

  html = html.trim()

  const doctypeIndex = html.toLowerCase().indexOf('<!doctype')
  const htmlIndex = html.toLowerCase().indexOf('<html')

  if (doctypeIndex >= 0) {
    html = html.slice(doctypeIndex)
  } else if (htmlIndex >= 0) {
    html = `<!doctype html>\n${html.slice(htmlIndex)}`
  }

  return html.trim()
}

function isValidWebsite(html: string): boolean {
  const value = html.toLowerCase()

  return (
    value.includes('<!doctype html>') &&
    value.includes('<html') &&
    value.includes('<head') &&
    value.includes('<body') &&
    value.includes('</html>')
  )
}

