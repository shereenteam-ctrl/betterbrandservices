async function callBbsAiModel(
  request: BbsAiRequest,
): Promise<string> {
  if (!ENGINE_URL) {
    throw new Error(
      'BBS_AI_ENGINE_URL is not configured. The BBS AI model server has not been connected yet.',
    )
  }

  const response = await fetch(ENGINE_URL, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      system: websiteSystemPrompt(),
      prompt: request.prompt,
      currentHtml: request.currentHtml || '',
    }),
  })

  if (!response.ok) {
    const errorText = await response.text().catch(() => '')

    throw new Error(
      `BBS AI model request failed (${response.status}). ${errorText}`,
    )
  }

  const data = (await response.json()) as BbsAiModelResponse

  const html =
    data.html ||
    data.content ||
    data.result ||
    ''

  return cleanHtml(html)
}

export async function generateWithBbsAI(
  request: BbsAiRequest,
): Promise<BbsAiResponse> {
  /*
   * If the real BBS AI model server exists, use it.
   *
   * If it does not exist yet, use the local fallback so the
   * website builder continues working while we build the
   * actual BBS AI model infrastructure.
   */
  if (ENGINE_URL) {
    const html = await callBbsAiModel(request)

    if (!isValidWebsite(html)) {
      throw new Error(
        'BBS AI generated an invalid website document.',
      )
    }

    return {
      html,
      source: 'bbs-ai-model',
    }
  }

  return {
    html: fallbackWebsite(request.prompt),
    source: 'fallback',
  }
}
